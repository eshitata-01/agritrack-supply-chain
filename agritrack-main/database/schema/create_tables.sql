-- AgriTrack Oracle schema
-- Run this script in the target Oracle schema (for example, SQL Developer).

CREATE TABLE CROP_DIM (
  crop_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crop_name VARCHAR2(100) NOT NULL UNIQUE,
  category VARCHAR2(60)
);

CREATE TABLE STAGE_DIM (
  stage_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage_name VARCHAR2(60) NOT NULL UNIQUE
);

CREATE TABLE ROUTE_DIM (
  route_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origin VARCHAR2(100) NOT NULL,
  destination VARCHAR2(100) NOT NULL,
  region VARCHAR2(100) NOT NULL,
  CONSTRAINT uq_route UNIQUE (origin, destination, region)
);

CREATE TABLE FACILITY_DIM (
  facility_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facility_name VARCHAR2(120) NOT NULL,
  region VARCHAR2(100) NOT NULL
);

CREATE TABLE DATE_DIM (
  date_key NUMBER PRIMARY KEY,
  full_date DATE NOT NULL UNIQUE,
  month_year VARCHAR2(7) NOT NULL
);

CREATE TABLE SHIPMENT_FACT (
  shipment_id NUMBER PRIMARY KEY,
  crop_key NUMBER NOT NULL REFERENCES CROP_DIM(crop_key),
  route_key NUMBER NOT NULL REFERENCES ROUTE_DIM(route_key),
  dispatch_date_key NUMBER NOT NULL REFERENCES DATE_DIM(date_key),
  qty_dispatched_kg NUMBER(12,2) NOT NULL CHECK (qty_dispatched_kg >= 0),
  qty_received_kg NUMBER(12,2) NOT NULL CHECK (qty_received_kg >= 0),
  status VARCHAR2(30) NOT NULL,
  CONSTRAINT chk_received_le_dispatched CHECK (qty_received_kg <= qty_dispatched_kg)
);

CREATE TABLE LOSS_EVENT_FACT (
  loss_event_id NUMBER PRIMARY KEY,
  shipment_id NUMBER NOT NULL REFERENCES SHIPMENT_FACT(shipment_id),
  stage_key NUMBER NOT NULL REFERENCES STAGE_DIM(stage_key),
  facility_key NUMBER NOT NULL REFERENCES FACILITY_DIM(facility_key),
  date_key NUMBER NOT NULL REFERENCES DATE_DIM(date_key),
  loss_kg NUMBER(12,2) NOT NULL CHECK (loss_kg >= 0),
  storage_days NUMBER(8,2)
);

CREATE INDEX idx_ship_crop ON SHIPMENT_FACT(crop_key);
CREATE INDEX idx_ship_route ON SHIPMENT_FACT(route_key);
CREATE INDEX idx_loss_ship ON LOSS_EVENT_FACT(shipment_id);
CREATE INDEX idx_loss_stage ON LOSS_EVENT_FACT(stage_key);
CREATE INDEX idx_loss_facility ON LOSS_EVENT_FACT(facility_key);
